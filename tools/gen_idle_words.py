#!/usr/bin/env python3
"""Render the complex script idle words to 1-bit bitmaps for the OLED idle show.

  py -3.14 tools/gen_idle_words.py            writes firmware/src/idle_words.h
  py -3.14 tools/gen_idle_words.py --sheet x.png   also writes a 5x preview sheet

Needs Pillow built with libraqm (text shaping: Devanagari and Bengali conjuncts,
Arabic and Urdu joining, right to left) and the Noto fonts in vendor/fonts/
(SIL Open Font License 1.1, not committed; only the rendered bitmaps are).

Method: render each word bold (wght 700) at 4x the pixel size, crop to the ink,
box filter down to 1x, threshold, crop again. The pixel size is the largest that
keeps the ink within the target height for the script.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont, features

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "vendor", "fonts")
OUT = os.path.join(ROOT, "firmware", "src", "idle_words.h")

SS = 4          # supersampling factor
THRESH = 110    # 0..255 after the box filter
WGHT = 700      # bold
MAX_H = 18      # the text band is y 12..29

# (C name, language name, text, font file, raqm language, direction, target ink height)
WORDS = [
    ("ZH", "Mandarin", "空闲", "NotoSansSC[wght].ttf", "zh", "ltr", 16),
    ("JA", "Japanese", "待機", "NotoSansJP[wght].ttf", "ja", "ltr", 16),
    ("HI", "Hindi", "निष्क्रिय",
     "NotoSansDevanagari[wdth,wght].ttf", "hi", "ltr", 16),
    ("BN", "Bengali", "নিষ্ক্রিয়",
     "NotoSansBengali[wdth,wght].ttf", "bn", "ltr", 17),
    ("AR", "Arabic", "خامل", "NotoSansArabic[wdth,wght].ttf", "ar", "rtl", 16),
    ("UR", "Urdu", "بیکار", "NotoSansArabic[wdth,wght].ttf", "ur", "rtl", 16),
]


def render(text, font_file, lang, direction, size):
    f = ImageFont.truetype(os.path.join(FONTS, font_file), size * SS, layout_engine=ImageFont.Layout.RAQM)
    axes = f.get_variation_axes()
    vals = []
    for a in axes:
        name = a["name"].decode() if isinstance(a["name"], bytes) else a["name"]
        vals.append(WGHT if name.lower().startswith("weight") else a["default"] if name != "Width" else 100)
    f.set_variation_by_axes(vals)
    im = Image.new("L", (size * SS * 14, size * SS * 4), 0)
    ImageDraw.Draw(im).text((size * SS, size * SS), text, font=f, fill=255, direction=direction, language=lang)
    im = im.crop(im.getbbox())
    im = im.resize((max(1, round(im.width / SS)), max(1, round(im.height / SS))), Image.BOX)
    b = im.point(lambda v: 255 if v >= THRESH else 0).convert("1")
    return b.crop(b.getbbox())


def best(word):
    _, _, text, font_file, lang, direction, target = word
    pick = None
    for size in range(10, 30):
        b = render(text, font_file, lang, direction, size)
        if b.height <= min(target, MAX_H):
            pick = b
        else:
            break
    return pick


def cols_of(b):
    px = b.load()
    out = []
    for x in range(b.width):
        v = 0
        for y in range(b.height):
            if px[x, y]:
                v |= 1 << y
        out.append(v)
    return out


def main(argv):
    if not features.check("raqm"):
        print("error: Pillow has no libraqm; shaping would be wrong", file=sys.stderr)
        return 1
    lines = [
        "/* GENERATED by tools/gen_idle_words.py: do not edit by hand.",
        " *",
        " * 1-bit bitmaps of the complex script idle words, rendered on the PC with Pillow",
        " * and libraqm (shaped: conjuncts, joining, right to left) from Noto Sans SC,",
        " * Noto Sans JP, Noto Sans Devanagari, Noto Sans Bengali and Noto Sans Arabic",
        " * (bold, wght 700). The fonts are under the SIL Open Font License 1.1; only these",
        " * rendered glyph bitmaps are in the firmware, the font files are not.",
        " *",
        " * Each column is one uint32_t, bit 0 the top row. */",
        "#ifndef IDLE_WORDS_H",
        "#define IDLE_WORDS_H",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint8_t w, h;  /* pixels; h <= 18 */",
        "    uint8_t rtl;   /* written right to left */",
        "    const uint32_t *cols;",
        "} idle_bmp_t;",
        "",
    ]
    bitmaps = []
    for word in WORDS:
        b = best(word)
        if b is None or b.width > 124:
            print("error: no fit for", word[1], file=sys.stderr)
            return 1
        bitmaps.append((word, b))
        cols = cols_of(b)
        lines.append("/* %s, %d x %d */" % (word[1], b.width, b.height))
        lines.append("static const uint32_t IDLE_BMP_%s_COLS[%d] = {" % (word[0], b.width))
        for i in range(0, len(cols), 8):
            lines.append("    " + ", ".join("0x%05X" % c for c in cols[i:i + 8]) + ",")
        lines.append("};")
        print("%-9s %3d x %2d" % (word[1], b.width, b.height))
    lines.append("")
    for word, b in bitmaps:
        lines.append("static const idle_bmp_t IDLE_BMP_%s = {%d, %d, %d, IDLE_BMP_%s_COLS};"
                     % (word[0], b.width, b.height, 1 if word[5] == "rtl" else 0, word[0]))
    lines += ["", "#endif", ""]
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)

    if len(argv) == 3 and argv[1] == "--sheet":
        s = 6
        sheet = Image.new("RGB", (130 * s, sum((b.height + 3) * s for _, b in bitmaps)), (5, 10, 18))
        y = 0
        for _, b in bitmaps:
            sheet.paste(b.convert("RGB").resize((b.width * s, b.height * s), Image.NEAREST), (s, y))
            y += (b.height + 3) * s
        sheet.save(argv[2])
        print("wrote", argv[2])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
