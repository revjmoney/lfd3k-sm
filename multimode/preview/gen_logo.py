"""Generates multimode/picker/src/logo_bitmaps.h: the AXIS letters for the
picker splash, drawn here from simple geometry on a pixel grid (no font).
Run:  py -3.14 multimode/preview/gen_logo.py
"""
import os

H = 26  # letter height in pixels


def blank(w):
    return [[0] * w for _ in range(H)]


def put(g, x, y):
    if 0 <= y < H and 0 <= x < len(g[0]):
        g[y][x] = 1


def span(g, y, x0, x1):
    for x in range(int(round(x0)), int(round(x1)) + 1):
        put(g, x, y)


def letter_a():
    w = 30
    g = blank(w)
    top_l, top_r = 11, 18  # flat top
    stroke = 7
    for y in range(H):
        f = y / (H - 1)
        ol = top_l - top_l * f          # outer left edge
        orr = top_r + (w - 1 - top_r) * f
        span(g, y, ol, ol + stroke - 1)
        span(g, y, orr - stroke + 1, orr)
        if y <= 3:
            span(g, y, ol, orr)        # solid top
        if 16 <= y <= 19:
            span(g, y, ol, orr)        # crossbar
    return g


def letter_x():
    w = 24
    g = blank(w)
    stroke = 7
    for y in range(H):
        f = y / (H - 1)
        a = (w - stroke) * f
        span(g, y, a, a + stroke - 1)
        b = (w - stroke) * (1 - f)
        span(g, y, b, b + stroke - 1)
    return g


def letter_i():
    w = 7
    g = blank(w)
    for y in range(H):
        span(g, y, 0, w - 1)
    return g


def letter_s():
    w = 22
    g = blank(w)
    t = 5   # bar thickness
    v = 7   # stem width
    mid0 = (H - t) // 2
    for y in range(H):
        if y < t:
            span(g, y, 0, w - 1)
        if mid0 <= y < mid0 + t:
            span(g, y, 0, w - 1)
        if y >= H - t:
            span(g, y, 0, w - 1)
        if y < mid0 + t:
            span(g, y, 0, v - 1)
        if y >= mid0:
            span(g, y, w - v, w - 1)
    # chamfer the outer corners (3 px steps) for a machined look
    for k in range(3):
        for j in range(3 - k):
            g[k][j] = 0                    # top left
            g[H - 1 - k][w - 1 - j] = 0    # bottom right
            g[mid0 + t - 1 - k][j] = 0      # mid left, lower
            g[mid0 + k][w - 1 - j] = 0      # mid right, upper
    return g


def emit(letters):
    out = []
    out.append("/* AXIS letters for the picker splash, generated by")
    out.append(" * multimode/preview/gen_logo.py from simple geometry (no font).")
    out.append(" * Each letter is %d rows; bit (w - 1 - x) of a row word is pixel x. */" % H)
    out.append("#ifndef LOGO_BITMAPS_H")
    out.append("#define LOGO_BITMAPS_H")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("#define LOGO_H %d" % H)
    out.append("")
    for name, g in letters:
        w = len(g[0])
        out.append("#define LOGO_%s_W %d" % (name, w))
        out.append("static const uint32_t LOGO_%s[LOGO_H] = {" % name)
        for row in g:
            v = 0
            for x, b in enumerate(row):
                if b:
                    v |= 1 << (w - 1 - x)
            art = "".join("#" if b else "." for b in row)
            out.append("    0x%08X, /* %s */" % (v, art))
        out.append("};")
        out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(here, "..", "picker", "src", "logo_bitmaps.h")
    letters = [("A", letter_a()), ("X", letter_x()), ("I", letter_i()), ("S", letter_s())]
    with open(dst, "w", newline="\n") as f:
        f.write(emit(letters))
    for name, g in letters:
        print(name)
        for row in g:
            print("".join("#" if b else "." for b in row))


if __name__ == "__main__":
    main()
